//! Boolean expression types and traits.

use cvlr_asserts::{cvlr_assert, cvlr_assume};

/// A Boolean expression that can be evaluated, assumed, or asserted.
///
/// This trait represents a boolean expression with an associated context type.
/// Expressions implementing this trait can be:
/// - Evaluated to a boolean value via [`eval`](CvlrFormula::eval) (single state)
/// - Evaluated over two states via [`eval_with_states`](CvlrFormula::eval_with_states) (pre-state and post-state)
/// - Asserted (checked) via [`assert`](CvlrFormula::assert) or [`assert_with_states`](CvlrFormula::assert_with_states)
/// - Assumed (taken as a precondition) via [`assume`](CvlrFormula::assume) or [`assume_with_states`](CvlrFormula::assume_with_states)
///
/// # Associated Types
///
/// * [`Context`](CvlrFormula::Context) - The context type used to evaluate the expression. This typically
///   represents the state or environment in which the expression is evaluated.
///
/// # Single-state and two-state formulas
///
/// A *single-state* formula describes one state and implements
/// [`eval`](CvlrFormula::eval) (and, optionally, `assert`/`assume`). It can be
/// used anywhere, including as the ensures clause of a spec, where the
/// default `*_with_states` methods apply it to the post-state.
///
/// A *two-state* formula relates a post-state to a pre-state and overrides the
/// `*_with_states` methods. In every `*_with_states` method, **`ctx0` is the
/// post-state and `ctx1` is the pre-state** (this is how
/// [`CvlrSpec::check_ensures`](crate::CvlrSpec::check_ensures) calls them). Two-state
/// formulas can only be used where two states are available, such as an
/// ensures clause; the ones generated by
/// [`cvlr_def_states_predicate!`](crate::cvlr_def_states_predicate) and
/// two-parameter `#[cvlr::predicate]` functions fail the rule (`cvlr_assert!(false)`)
/// if their single-state methods are called, e.g. when used as a requires
/// clause or an invariant.
///
/// Usually a formula is not implemented by hand but generated with
/// `#[cvlr::predicate]`, [`cvlr_def_predicate!`](crate::cvlr_def_predicate) or
/// [`cvlr_predicate!`](crate::cvlr_predicate), and combined with
/// [`cvlr_and!`](crate::cvlr_and!) and [`cvlr_implies!`](crate::cvlr_implies!).
/// Generated formulas assert and assume each of their conditions separately,
/// so a failing assertion identifies the condition that failed.
///
/// # Examples
///
/// ```
/// use cvlr_spec::CvlrFormula;
///
/// struct MyContext {
///     value: i32,
/// }
///
/// struct IsPositive;
///
/// impl CvlrFormula for IsPositive {
///     type Context = MyContext;
///     fn eval(&self, ctx: &Self::Context) -> bool {
///         ctx.value > 0
///     }
/// }
/// ```
pub trait CvlrFormula {
    /// The type of state the formula is evaluated on.
    type Context;

    /// Evaluates the expression in the given context.
    ///
    /// Returns `true` if the expression holds, `false` otherwise.
    fn eval(&self, ctx: &Self::Context) -> bool;

    /// Asserts that the expression holds in the given context.
    ///
    /// This will cause a verification failure if the expression evaluates to `false`.
    /// The default implementation uses [`cvlr_assert!`] to check the result of [`eval`](CvlrFormula::eval).
    /// Override it to assert the parts of the formula separately (and log
    /// their values), which makes counterexamples easier to read.
    fn assert(&self, ctx: &Self::Context) {
        cvlr_assert!(self.eval(ctx));
    }

    /// Assumes that the expression holds in the given context.
    ///
    /// This adds the expression as a precondition that the verifier will assume to be true.
    /// The default implementation uses [`cvlr_assume!`] to assume the result of [`eval`](CvlrFormula::eval).
    fn assume(&self, ctx: &Self::Context) {
        cvlr_assume!(self.eval(ctx));
    }

    /// Evaluates the expression over two states (post-state and pre-state).
    ///
    /// This method allows expressions to be evaluated in contexts that require
    /// comparing values from two different states, such as checking invariants
    /// across state transitions or comparing before and after values.
    ///
    /// # Parameters
    ///
    /// * `ctx0` - The post-state context (after the transition)
    /// * `ctx1` - The pre-state context (before the transition)
    ///
    /// # Returns
    ///
    /// Returns `true` if the expression holds across both states, `false` otherwise.
    ///
    /// # Default Implementation
    ///
    /// The default implementation evaluates the expression using only the post-state
    /// context (`ctx0`). Expressions that need to compare both states should override
    /// this method.
    fn eval_with_states(&self, ctx0: &Self::Context, _: &Self::Context) -> bool {
        self.eval(ctx0)
    }

    /// Asserts that the expression holds across two states (post-state and pre-state).
    ///
    /// This will cause a verification failure if the expression evaluates to `false`
    /// when considering both the post-state and pre-state contexts.
    ///
    /// # Parameters
    ///
    /// * `ctx0` - The post-state context (after the transition)
    /// * `ctx1` - The pre-state context (before the transition)
    ///
    /// # Default Implementation
    ///
    /// The default implementation asserts the expression using only the post-state
    /// context (`ctx0`). Expressions that need to compare both states should override
    /// this method.
    fn assert_with_states(&self, ctx0: &Self::Context, _: &Self::Context) {
        self.assert(ctx0);
    }

    /// Assumes that the expression holds across two states (post-state and pre-state).
    ///
    /// This adds the expression as a precondition that the verifier will assume to be true
    /// when considering both the post-state and pre-state contexts.
    ///
    /// # Parameters
    ///
    /// * `ctx0` - The post-state context (after the transition)
    /// * `ctx1` - The pre-state context (before the transition)
    ///
    /// # Default Implementation
    ///
    /// The default implementation assumes the expression using only the post-state
    /// context (`ctx0`). Expressions that need to compare both states should override
    /// this method.
    fn assume_with_states(&self, ctx0: &Self::Context, _: &Self::Context) {
        self.assume(ctx0);
    }
}

/// Marker for a named predicate type.
///
/// Implemented automatically for every type generated by
/// [`cvlr_def_predicate!`](crate::cvlr_def_predicate),
/// [`cvlr_def_states_predicate!`](crate::cvlr_def_states_predicate),
/// [`cvlr_def_predicates!`](crate::cvlr_def_predicates),
/// [`cvlr_def_states_predicates!`](crate::cvlr_def_states_predicates) and the
/// `#[cvlr::predicate]` attribute. Such a type is a unit struct, so it can be
/// named in type position (e.g. as a spec's requires/ensures) and constructed
/// by writing its name; `cvlr::pif!(fn_name)` gives the struct name for a
/// `#[cvlr::predicate]` function.
///
/// The trait adds no methods beyond [`CvlrFormula`], and no CVLR API requires
/// it as a bound: any [`CvlrFormula`] can be used wherever a formula is
/// expected. There is no need to implement it by hand.
pub trait CvlrPredicate: CvlrFormula {}

/// A boolean expression that always evaluates to `true`.
///
/// This is a constant expression that can be used as a base case or placeholder
/// in boolean expression compositions.
#[derive(Copy, Clone)]
pub struct CvlrTrue<Ctx>(core::marker::PhantomData<Ctx>);

impl<Ctx> CvlrFormula for CvlrTrue<Ctx> {
    type Context = Ctx;
    fn eval(&self, _ctx: &Self::Context) -> bool {
        true
    }
    fn assert(&self, _ctx: &Self::Context) {}
    fn assume(&self, _ctx: &Self::Context) {}
}

/// Returns a formula over context `Ctx` that is always `true`.
///
/// `eval` and `eval_with_states` return `true`, and `assert`/`assume` (and
/// their `_with_states` forms) emit nothing, so it adds no proof obligation and
/// no assumption. Use it as the requires clause of a spec with no precondition,
/// the ensures clause of a spec with no postcondition, or a neutral element
/// when building formulas with [`cvlr_and`](fn@crate::cvlr_and) /
/// [`cvlr_implies`](fn@crate::cvlr_implies).
///
/// The context type usually has to be given explicitly, since nothing else
/// constrains it:
///
/// ```
/// use cvlr_spec::{cvlr_true, CvlrFormula};
///
/// struct Ctx;
/// assert!(cvlr_true::<Ctx>().eval(&Ctx));
/// ```
pub fn cvlr_true<Ctx>() -> impl CvlrFormula<Context = Ctx> {
    CvlrTrue(core::marker::PhantomData)
}
